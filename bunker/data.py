def calculate_bunker_capacity(num_players: int) -> int:
    """
    Рассчитывает количество мест в бункере на основе числа участников:
    - 2 игрока: 1 место (85%), 2 места (15%)
    - 3 игрока: 1 место (40%), 2 места (45%), 3 места (15%)
    - N игроков: от 1 до N-1 мест (в среднем ~50% от числа игроков)
    """
    if num_players <= 1:
        return 1
    if num_players == 2:
        return random.choices([1, 2], weights=[85, 15])[0]
    if num_players == 3:
        return random.choices([1, 2, 3], weights=[40, 45, 15])[0]

    min_cap = max(1, int(num_players * 0.3))
    max_cap = max(1, num_players - 1)
    avg_cap = max(1, int(num_players * 0.5))
    return random.choice([min_cap, avg_cap, max_cap])


