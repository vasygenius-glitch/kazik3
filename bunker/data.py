def calculate_bunker_capacity(num_players: int) -> int:
    """
    Рассчитывает количество мест в бункере на основе числа участников (примерно половина мест):
    - 2 игрока: 1 место (85%), 2 места (15%)
    - 3 игрока: 1 место (40%), 2 места (45%), 3 места (15%)
    - N игроков: max(1, num_players // 2)
    """
    if num_players <= 1:
        return 1
    if num_players == 2:
        return random.choices([1, 2], weights=[85, 15])[0]
    if num_players == 3:
        return random.choices([1, 2, 3], weights=[40, 45, 15])[0]

    return max(1, num_players // 2)


